function parseBoldSpans(text: string): { text: string; bold: boolean }[] {
  const parts: { text: string; bold: boolean }[] = [];
  const regex = /\*\*(.*?)\*\*/g;
  let lastIndex = 0;
  let match;

  while ((match = regex.exec(text)) !== null) {
    if (match.index > lastIndex) {
      parts.push({ text: text.substring(lastIndex, match.index), bold: false });
    }
    parts.push({ text: match[1], bold: true });
    lastIndex = regex.lastIndex;
  }

  if (lastIndex < text.length) {
    parts.push({ text: text.substring(lastIndex), bold: false });
  }

  return parts.length > 0 ? parts : [{ text, bold: false }];
}

function extractMarkdownSections(content: string): { title: string; bullets: string[] }[] {
  const lines = content.split('\n');
  const sections: { title: string; bullets: string[] }[] = [];
  let currentTitle = '';
  let currentBullets: string[] = [];

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('# ') || trimmed.startsWith('## ') || trimmed.startsWith('### ')) {
      if (currentTitle && currentBullets.length > 0) {
        sections.push({ title: currentTitle, bullets: [...currentBullets] });
        currentBullets = [];
      }
      currentTitle = trimmed.replace(/^#+\s+/, '');
    } else if (trimmed.startsWith('- ') || trimmed.startsWith('* ') || /^\d+\.\s+/.test(trimmed)) {
      currentBullets.push(trimmed.replace(/^[-*\d.]+\s+/, '').replace(/\*\*/g, ''));
    } else if (trimmed.length > 20 && !trimmed.startsWith('```')) {
      if (currentBullets.length < 5) {
        currentBullets.push(trimmed.replace(/\*\*/g, ''));
      }
    }
  }

  if (currentTitle && currentBullets.length > 0) {
    sections.push({ title: currentTitle, bullets: currentBullets });
  }

  return sections;
}

